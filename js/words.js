/** 占卜師提示：第一個字的部首 + 字數 */
export function hintFor(word) {
  const chars = [...word];
  return { radical: RADICALS[chars[0]] || '？', length: chars.length };
}

/** 隨機抽 n 個詞，避開 exclude 中的詞（全部用過時就不避開） */
export function drawWords(difficulty, n, exclude = new Set(), avoid = []) {
  const pool = WORDS[difficulty];
  let fresh = pool.filter((w) => !exclude.has(w) && !avoid.includes(w));
  if (fresh.length < n) fresh = pool.filter((w) => !avoid.includes(w));
  if (fresh.length < n) fresh = pool.slice();
  const out = [];
  while (out.length < n && fresh.length) {
    out.push(fresh.splice(Math.floor(Math.random() * fresh.length), 1)[0]);
  }
  return out;
}
